type BaseTranslationKey = keyof typeof baseTranslations.en

const esTranslations: Record<BaseTranslationKey, string> = {
  ...baseTranslations.en,
  ...spanishTranslations,
}

export const translations = {
  ...baseTranslations,
  es: esTranslations,
} as const

type TranslationKey = BaseTranslationKey

interface I18nContextValue {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: TranslationKey, replacements?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

function isLanguage(value: string | null): value is Language {
  return value === "en" || value === "pt-BR" || value === "es"
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(DEFAULT_LANGUAGE)

  useEffect(() => {
    const savedLanguage = window.localStorage.getItem(LANGUAGE_STORAGE_KEY)
    if (isLanguage(savedLanguage)) {
      setLanguageState(savedLanguage)
    }
  }, [])

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const setLanguage = useCallback((nextLanguage: Language) => {
    setLanguageState(nextLanguage)
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage)
  }, [])

  const t = useCallback(
    (key: TranslationKey, replacements?: Record<string, string | number>) => {
      let value: string = translations[language][key] ?? translations.en[key] ?? key
      if (replacements) {
        for (const [name, replacement] of Object.entries(replacements)) {
          value = value.replaceAll(`{${name}}`, String(replacement))
        }
      }
      return value
    },
    [language]
  )

  const contextValue = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t])

  return <I18nContext.Provider value={contextValue}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) {
    throw new Error("useI18n must be used within I18nProvider")
  }
  return context
}
